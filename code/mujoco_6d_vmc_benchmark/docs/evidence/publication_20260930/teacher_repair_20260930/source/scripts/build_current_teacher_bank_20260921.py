"""Build a current four-family VMC action-teacher bank.

The historical ball/corner bank is reused only after its READY certificate is
checked. Push episodes come exclusively from the 2026-09-20 workstation
search and therefore use the accepted raised end-effector guard geometry.
No learner is trained here. Splits are by parameter group, never by adjacent
windows from the same rollout.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import numpy as np

SCENES=("ball","push","corner","table_corner")


def sha(value):
    return hashlib.sha256(json.dumps(value,sort_keys=True,separators=(",",":")).encode()).hexdigest()


def split_group(group, seed=20260921):
    h=int(hashlib.sha256(f"{seed}:{group}".encode()).hexdigest()[:8],16)/0xffffffff
    return "train" if h<.70 else "validation" if h<.85 else "test"


def canonical(src, dst, teacher_key="teacher_action"):
    with np.load(src,allow_pickle=False) as z:
        obs=np.asarray(z["observation"],dtype=np.float32)
        action=np.asarray(z[teacher_key],dtype=np.float32)
        if "command_time_s" in z:
            t=np.asarray(z["command_time_s"],dtype=np.float64)
        elif "time" in z:
            t=np.asarray(z["time"],dtype=np.float64)
        else:
            t=np.arange(len(obs),dtype=np.float64)*.04
    if obs.ndim!=2 or obs.shape[1]!=45 or action.shape!=(len(obs),7):
        raise ValueError(f"schema {src}: {obs.shape} {action.shape}")
    if not np.isfinite(obs).all() or not np.isfinite(action).all():raise ValueError(f"nonfinite {src}")
    if len(t)>1 and not np.allclose(np.diff(t),.04,atol=2e-4):raise ValueError(f"time grid {src}")
    dst.parent.mkdir(parents=True,exist_ok=True)
    np.savez_compressed(dst,observation=obs,teacher_action=action,command_time_s=t,dt_s=np.float64(.04))
    return len(obs),hashlib.sha256(obs.tobytes()+action.tobytes()).hexdigest()


def old_rows(old_root, scene):
    m=json.load(open(old_root/"manifest.json")); rows=[]
    # Use train_clean/validation/test from the independently audited bank.
    for split in ("train_clean","validation","test"):
        for row in m[split]:
            if row["scene"]!=scene:continue
            group=row.get("parameter_group") or row.get("fixture_hash") or row.get("parent_group")
            if scene in ("corner","table_corner"):
                result_path=row.get("result")
                if result_path and Path(result_path).exists():
                    result=json.load(open(result_path)); bodies=set((result.get("contact") or {}).get("robot_bodies",[])) | set((result.get("panel_audit") or {}).get("robot_bodies",[]))
                    if bodies & {"fr3_link3","fr3_link4","fr3_link5","fr3_link6","fr3_link7"}: continue
            rows.append(dict(scene=scene,split=split_group(group),source_trace=row["trace"],source_result=row.get("result"),
                parameter_group=row.get("parameter_group"),fixture_hash=row.get("fixture_hash"),
                teacher_family=row.get("teacher_family"),teacher_force=row.get("teacher_force"),
                source_bank="four_scene_pareto_teacher_v1_20260918",accepted=True))
    return rows


def push_rows(search_root, groups=("combined","rear_combined")):
    state=json.load(open(search_root/"state.json"));rows=[]
    for group in groups:
        for h in state["history"]:
            if h.get("group")!=group or not h.get("accepted"):continue
            result_file=Path(h["result_file"])
            if not result_file.exists():continue
            result=json.load(open(result_file));metrics=result.get("metrics",{})
            contacts=metrics.get("contacts",{})
            invalid=False
            for cname,crow in contacts.items():
                if cname in ("target_object_geom",): continue
                if set(crow.get("bodies",[])) & {"fr3_link3","fr3_link4","fr3_link5","fr3_link6","fr3_link7"}: invalid=True
            if invalid: continue
            # The trial directory contains rollout.npz generated by the
            # current physical workstation scene.
            trace=result_file.parent/"rollout.npz"
            if not trace.exists():continue
            cfg=h["config"]
            parameter_group=sha(cfg)
            rows.append(dict(scene="push",split=split_group(parameter_group),source_trace=str(trace),
                source_result=str(result_file),parameter_group=parameter_group,
                fixture_hash=sha({"group":group,"panel":"raised_hand_rim","workstation":True}),
                teacher_family="six_d_vmc_open_workstation_raised_hand_rim",
                teacher_force="estimated_proprioceptive_wrench",source_bank="vmc_auto_search_20260920",
                search_group=group,search_id=h["id"],metrics=metrics,accepted=True))
    # Deduplicate exact content hashes while retaining parameter provenance.
    unique={}
    for row in rows:
        with np.load(row["source_trace"],allow_pickle=False) as z:
            key=hashlib.sha256(z["observation"].tobytes()+z["teacher_action"].tobytes()).hexdigest()
        row["content_hash"]=key;unique.setdefault(key,row)
    return list(unique.values())


def main():
    ap=argparse.ArgumentParser();ap.add_argument("--output",type=Path,required=True);ap.add_argument("--old-bank",type=Path,required=True);ap.add_argument("--search",type=Path,required=True);a=ap.parse_args()
    old=a.old_bank;out=a.output;out.mkdir(parents=True,exist_ok=True)
    ready=json.load(open(old/"READY.json"));cert=json.load(open(old/"quality_certificate.json"))
    if not ready.get("ready") or not cert.get("ready"):raise RuntimeError("old bank is not independently READY")
    rows=[]
    for scene in ("ball","corner","table_corner"):rows.extend(old_rows(old,scene))
    push=push_rows(a.search)
    if len(push)<100:raise RuntimeError(f"current push bank too small: {len(push)}")
    rows.extend(push)
    # Canonical export and a fresh group-disjoint split. Historical rows keep
    # their audited split; push rows are assigned by parameter group above.
    manifest=[];counts={s:{k:0 for k in ("train","validation","test")} for s in SCENES};groups={s:{k:set() for k in counts[s]} for s in SCENES}
    for i,row in enumerate(rows):
        split="train" if row["split"] in ("train","train_clean") else row["split"];scene=row["scene"]
        source=Path(row["source_trace"])
        # old manifest paths are absolute on the server; reject accidental
        # local/nonexistent paths instead of silently making empty records.
        if not source.exists():raise FileNotFoundError(source)
        rel=Path("dataset")/"episodes"/scene/f"{scene}_{i:05d}.npz"
        samples,content=canonical(source,out/rel)
        rec=dict(row,split=split,id=f"{scene}_{i:05d}",trace=str(rel),samples=samples,content_hash=content)
        manifest.append(rec);counts[scene][split]+=1;groups[scene][split].add(row.get("parameter_group") or row.get("fixture_hash"))
    # Verify group separation and content duplication.
    for scene in SCENES:
        for x,y in (("train","validation"),("train","test"),("validation","test")):
            overlap=groups[scene][x]&groups[scene][y]
            if overlap:raise RuntimeError(f"group leakage {scene} {x}/{y}: {len(overlap)}")
    hashes={}
    for row in manifest:
        if row["content_hash"] in hashes:raise RuntimeError(f"duplicate trace content {row['id']} {hashes[row['content_hash']]}")
        hashes[row["content_hash"]]=row["id"]
    payload=dict(version="current_vmc_teacher_bank_20260921",student_training_started=False,
        scenes=SCENES,contract="action distillation: 45D proprioceptive observation -> 7D VMC action",
        teacher_information={
            "ball":"audited historical ball VMC bank; retained unchanged",
            "push":"current 2026-09-20 open workstation with raised end-effector front/back guards; replaced historical push bank",
            "corner":"audited historical pregrasp table-corner bank; retained unchanged",
            "table_corner":"audited historical loaded thick-table-corner placement bank; retained unchanged"},
        counts=counts,physical_groups={scene:{k:len(groups[scene][k]) for k in groups[scene]} for scene in SCENES},
        unique_parameter_groups={s:len({r.get("parameter_group") for r in manifest if r["scene"]==s}) for s in SCENES},
        rows=manifest,train_clean=[r for r in manifest if r["split"]=="train"],
        train=[r for r in manifest if r["split"]=="train"],
        validation=[r for r in manifest if r["split"]=="validation"],
        test=[r for r in manifest if r["split"]=="test"],
        source_banks={"old":str(old),"current_push":str(a.search)})
    (out/"manifest.json").write_text(json.dumps(payload,indent=2))
    train_rows=payload["train_clean"]
    total=0;mean=None;m2=None
    for row in train_rows:
        with np.load(out/row["trace"],allow_pickle=False) as z:
            x=z["observation"].astype(np.float64);total+=len(x)
            s=x.sum(0);q=(x*x).sum(0)
            mean=s if mean is None else mean+s;m2=q if m2 is None else m2+q
    mean=mean/max(total,1);std=np.sqrt(np.maximum(m2/max(total,1)-mean*mean,0.)).clip(min=.03)
    np.savez_compressed(out/"normalization_train_only.npz",mean=mean.astype(np.float32),std=std.astype(np.float32),samples=np.int64(total))
    ready=dict(ready=True,student_training_started=False,manifest_sha256=hashlib.sha256((out/"manifest.json").read_bytes()).hexdigest(),
        counts=counts,unique_parameter_groups=payload["unique_parameter_groups"],source_code_frozen=False)
    (out/"READY.json").write_text(json.dumps(ready,indent=2))
    summary=dict(ready=True,raw_episodes=len(manifest),counts=counts,physical_groups=payload["physical_groups"],
        unique_parameter_groups=payload["unique_parameter_groups"],push_source="vmc_auto_search_20260920",student_training_started=False,
        office_data_used=False,notes=["Push was rebuilt from current raised-hand workstation geometry.","Ball/corner banks are retained from the independently audited v1 bank.","This bank is teacher data; no MLP/ESN training has started."])
    (out/"summary.json").write_text(json.dumps(summary,indent=2))
    # Copy the actual current push selection metadata for traceability.
    shutil.copy2(a.search/"state.json",out/"push_search_state.json")
    print(json.dumps(summary,indent=2))


if __name__=="__main__":main()
