"""Fit an ESN readout on states visited by the frozen student.

This is the first DAgger-style diagnostic: the rollout is generated by the
frozen student, then the fixed 6-D VMC teacher relabels those observations.
The reservoir, normalization, first readout layer, action filter and gates are
unchanged.  The output is a development checkpoint and must be physically
validated before it can replace the frozen model.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np

from fit_esn_history_adapter_20260925 import (
    actions_from_logits,
    hidden_from_head,
    load_model,
    sha,
)
from run_vmc_6d_constrained_push_20260918 import SixDVirtualDynamics


def features_from_observation(model: dict, observation: np.ndarray) -> np.ndarray:
    observation = np.asarray(observation, dtype=np.float64)
    if observation.ndim != 2 or observation.shape[1] != 48:
        raise ValueError(f"expected N x 48 observation, got {observation.shape}")
    mean = np.asarray(model["mean"], dtype=np.float64)
    std = np.asarray(model["std"], dtype=np.float64)
    mask = np.asarray(model["input_mask"], dtype=np.float64)
    win = np.asarray(model["win"], dtype=np.float64)
    recurrent = np.asarray(model["w"], dtype=np.float64)
    leak = np.asarray(model["leak"], dtype=np.float64)
    state = np.zeros(128, dtype=np.float64)
    rows = []
    for row in observation:
        x = np.clip((row - mean) / std, -12.0, 12.0) * mask
        state += leak * (np.tanh(win @ np.r_[1.0, x] + recurrent @ state) - state)
        rows.append(np.r_[x, state])
    return np.asarray(rows)


def teacher_labels(observation: np.ndarray, config: dict) -> np.ndarray:
    teacher = SixDVirtualDynamics(config)
    labels = []
    for row in observation:
        labels.append(teacher.act(np.asarray(row[39:45], dtype=np.float64), 0.04))
    return np.asarray(labels, dtype=np.float64)


def stats(prediction: np.ndarray, target: np.ndarray) -> dict[str, float]:
    diff = prediction - target
    return {
        "action_rmse": float(np.sqrt(np.mean(diff * diff))),
        "action_mae": float(np.mean(np.abs(diff))),
        "x_sign_flip_fraction": float(np.mean(prediction[:, 1] * target[:, 1] < 0.0)),
        "nonfinite": float(np.sum(~np.isfinite(prediction))),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--checkpoint", type=Path, required=True)
    parser.add_argument("--rollout", type=Path, required=True)
    parser.add_argument("--teacher-config", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--proximal", type=float, default=1.0e-2)
    parser.add_argument("--on-policy-weight", type=float, default=8.0)
    args = parser.parse_args()
    if args.output.exists():
        raise FileExistsError(f"refusing to overwrite {args.output}")
    args.output.mkdir(parents=True)
    model = load_model(args.checkpoint)
    with np.load(args.rollout, allow_pickle=False) as z:
        observation = z["observation"].astype(np.float64)
    config = json.loads(args.teacher_config.read_text())
    features = features_from_observation(model, observation)
    target = teacher_labels(observation, config)
    fmean = np.asarray(model["fmean"], dtype=np.float64)
    fstd = np.asarray(model["fstd"], dtype=np.float64)
    x = (features - fmean) / fstd
    hidden = hidden_from_head(x, np.asarray(model["w1"], dtype=np.float64), np.asarray(model["b1"], dtype=np.float64))
    design = np.c_[hidden, np.ones(len(hidden))]
    logits = np.arctanh(np.clip(target, -0.999, 0.999))
    p = np.clip(target[:, 0], 1.0e-4, 1.0 - 1.0e-4)
    logits[:, 0] = np.log(p / (1.0 - p))
    base_w2 = np.asarray(model["w2"], dtype=np.float64)
    base_b2 = np.asarray(model["b2"], dtype=np.float64)
    base_weights = np.vstack((base_w2.T, base_b2))
    lhs = args.on_policy_weight * (design.T @ design)
    rhs = args.on_policy_weight * (design.T @ logits)
    regularizer = args.proximal * np.eye(design.shape[1], dtype=np.float64)
    regularizer[-1, -1] *= 0.1
    lhs += regularizer
    rhs += args.proximal * base_weights
    weights = np.linalg.solve(lhs, rhs)
    adapted_w2, adapted_b2 = weights[:-1], weights[-1]
    base_prediction = actions_from_logits(hidden @ base_w2.T + base_b2)
    adapted_prediction = actions_from_logits(hidden @ adapted_w2 + adapted_b2)
    output_checkpoint = args.output / "onpolicy_adapted.npz"
    metadata = {
        "method": "student_on_policy_vmc_relabel_readout",
        "scope": "development DAgger iteration; physical rollout required",
        "base_checkpoint_sha256": sha(args.checkpoint),
        "rollout_sha256": sha(args.rollout),
        "teacher_config_sha256": hashlib.sha256(args.teacher_config.read_bytes()).hexdigest(),
        "teacher_contract": "SixDVirtualDynamics on observation[39:45] at dt=0.04",
        "frozen_components": ["48D normalization", "reservoir", "first readout layer", "action projection", "safety filter", "task gates"],
        "on_policy_weight": args.on_policy_weight,
        "proximal_weight": args.proximal,
        "limitations": ["single development fixture", "labels are teacher relabels, not task success", "no validation fixture used for selection"],
    }
    with output_checkpoint.open("wb") as stream:
        np.savez_compressed(
            stream,
            contract="proprio48_esn128_action7_v1",
            metadata=json.dumps(metadata),
            seed=np.int64(model["seed"]),
            mean=np.asarray(model["mean"]), std=np.asarray(model["std"]),
            win=np.asarray(model["win"]), w=np.asarray(model["w"]), leak=np.asarray(model["leak"]),
            input_mask=np.asarray(model["input_mask"]), alpha=np.float64(model["alpha"]),
            output_gain=np.float64(model["output_gain"]), fmean=np.asarray(model["fmean"]),
            fstd=np.asarray(model["fstd"]), w1=np.asarray(model["w1"]), b1=np.asarray(model["b1"]),
            w2=adapted_w2.T, b2=adapted_b2,
        )
    report = {
        **metadata,
        "checkpoint_sha256": sha(output_checkpoint),
        "samples": int(len(observation)),
        "base_on_policy": stats(base_prediction, target),
        "adapted_on_policy": stats(adapted_prediction, target),
    }
    (args.output / "report.json").write_text(json.dumps(report, indent=2, allow_nan=False) + "\n")
    (args.output / "REPORT.md").write_text(
        "# ESN on-policy VMC relabel diagnostic\n\n"
        "This checkpoint is a DAgger-style development iteration. It uses a frozen student rollout and relabels the visited 48-D states with the fixed VMC teacher. It is not a task result until physically rolled out.\n\n"
        f"- samples: `{len(observation)}`\n- checkpoint SHA256: `{report['checkpoint_sha256']}`\n"
        f"- base action RMSE on relabeled states: `{report['base_on_policy']['action_rmse']:.6f}`\n"
        f"- adapted action RMSE on relabeled states: `{report['adapted_on_policy']['action_rmse']:.6f}`\n"
    )
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
