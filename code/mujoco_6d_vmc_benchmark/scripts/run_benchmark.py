#!/usr/bin/env python3
"""Run a fixed-reference 6D end-effector VMC stiffness sweep in MuJoCo.

The script purposefully keeps the reference source separate from the virtual
model controller.  It is therefore usable first with the deterministic
reaching proxy below and later with a cached or live fixed-WBC reference.
"""

from __future__ import annotations

import argparse
import json
import math
import os
import re
from dataclasses import asdict, dataclass, replace
from pathlib import Path
from typing import Any

import imageio.v3 as iio
import mujoco
import numpy as np


ARM_DOF = 7
CONTROL_DT = 0.004
SIM_TIME_S = 7.0
INTERVENTION_TIME_S = 3.15
OBSTACLE_CROSSING_TIME_S = 4.10
RENDER_FPS = 25
EPS = 1e-9
DEFAULT_CONTACT_TIME_CONSTANT_S = 0.10

# Conservative arm torque limits used by the torque controller.  The first
# four values follow the standard Panda joint capability; distal values are
# intentionally conservative for this first stability benchmark.
TORQUE_LIMITS = np.array([87.0, 87.0, 87.0, 87.0, 12.0, 12.0, 12.0])


def _skew(vector: np.ndarray) -> np.ndarray:
    x, y, z = vector
    return np.array([[0.0, -z, y], [z, 0.0, -x], [-y, x, 0.0]])


def so3_log(rotation: np.ndarray) -> np.ndarray:
    """Return the principal rotation vector for a 3x3 rotation matrix."""

    cosine = float(np.clip((np.trace(rotation) - 1.0) * 0.5, -1.0, 1.0))
    angle = math.acos(cosine)
    if angle < 1e-7:
        return np.array(
            [rotation[2, 1] - rotation[1, 2], rotation[0, 2] - rotation[2, 0], rotation[1, 0] - rotation[0, 1]]
        ) * 0.5
    axis = np.array(
        [rotation[2, 1] - rotation[1, 2], rotation[0, 2] - rotation[2, 0], rotation[1, 0] - rotation[0, 1]]
    ) / (2.0 * math.sin(angle))
    return angle * axis


def integrate_orientation(rotation: np.ndarray, angular_velocity: np.ndarray, dt: float) -> np.ndarray:
    """First-order SO(3) integration, adequate at this small fixed dt."""

    theta = float(np.linalg.norm(angular_velocity) * dt)
    if theta < 1e-10:
        return rotation
    axis = angular_velocity / (np.linalg.norm(angular_velocity) + EPS)
    update = np.eye(3) + math.sin(theta) * _skew(axis) + (1.0 - math.cos(theta)) * (_skew(axis) @ _skew(axis))
    return update @ rotation


def saturated_spring(stiffness: np.ndarray, saturation: np.ndarray, error: np.ndarray) -> np.ndarray:
    return saturation * np.tanh(stiffness * error / saturation)


@dataclass(frozen=True)
class VMCConfig:
    """Physical baseline values before the single ``kappa`` multiplier."""

    k_translation_base: float = 220.0  # N/m
    k_rotation_base: float = 18.0  # Nm/rad
    zeta: float = 1.05
    virtual_mass: float = 1.25  # kg per translation direction
    virtual_inertia: float = 0.08  # kg m^2 per rotational direction
    carriage_drive_k_translation: float = 75.0
    carriage_drive_k_rotation: float = 7.0
    carriage_drive_zeta: float = 1.15
    max_force: float = 24.0  # N per Cartesian channel
    max_moment: float = 3.0  # Nm per rotational channel
    max_carriage_speed: float = 0.55
    max_carriage_angular_speed: float = 1.25
    # Per-joint torque slew limits keep a finite virtual-wrench update from
    # becoming a one-frame motor impulse on impact or release.
    max_torque_rate_proximal: float = 700.0  # Nm/s, joints 1--4
    max_torque_rate_distal: float = 160.0  # Nm/s, joints 5--7


class NominalReference:
    """Reachable fixed-reference proxy derived from a Panda joint target.

    It is deliberately a *reference source*, not another controller.  The
    endpoint comes from a joint configuration inside Panda's limits, and each
    end-effector sample is generated by forward kinematics.  This avoids the
    invalid situation where a hand-authored Cartesian offset is unreachable
    under its simultaneously frozen orientation.
    """

    def __init__(self, model: mujoco.MjModel, data: mujoco.MjData, hand_id: int) -> None:
        self.model = model
        self.hand_id = hand_id
        self.start_q = data.qpos[:ARM_DOF].copy()
        # A compact, reachable movement away from Panda's home posture.  It
        # leaves margin to every joint range and does not alter the gripper.
        self.goal_q = np.array([0.38, -0.30, 0.28, -1.26, -0.34, 1.35, -0.48])
        self.rise_time = 5.4
        self._work = mujoco.MjData(model)
        self._work.qpos[:] = data.qpos
        self._work.qvel[:] = 0.0

    def sample(self, time_s: float) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
        phase = float(np.clip(time_s / self.rise_time, 0.0, 1.0))
        blend = 3.0 * phase**2 - 2.0 * phase**3
        blend_dot = 0.0 if time_s >= self.rise_time else (6.0 * phase - 6.0 * phase**2) / self.rise_time
        q = self.start_q + blend * (self.goal_q - self.start_q)
        qdot = blend_dot * (self.goal_q - self.start_q)
        self._work.qpos[:ARM_DOF] = q
        self._work.qvel[:ARM_DOF] = qdot
        mujoco.mj_forward(self.model, self._work)
        position = self._work.xpos[self.hand_id].copy()
        rotation = self._work.xmat[self.hand_id].reshape(3, 3).copy()
        twist = body_twist(self.model, self._work, self.hand_id)
        return position, rotation, twist[:3], twist[3:]


class SixDVirtualCarriage:
    """Six nonlinear virtual springs coupled through the physical arm."""

    def __init__(self, config: VMCConfig, kappa: float | np.ndarray, position: np.ndarray, rotation: np.ndarray) -> None:
        self.config = config
        self.position = position.copy()
        self.rotation = rotation.copy()
        self.linear_velocity = np.zeros(3)
        self.angular_velocity = np.zeros(3)

        self.mass = np.array([config.virtual_mass] * 3 + [config.virtual_inertia] * 3)
        self.saturation = np.array([config.max_force] * 3 + [config.max_moment] * 3)

        self.kappa_vector = np.ones(6, dtype=float)
        self.kappa = 1.0  # Backward-compatible scalar summary for old callers.
        self.stiffness = np.zeros(6, dtype=float)
        self.damping = np.zeros(6, dtype=float)
        self.set_kappas(kappa)

        self.drive_stiffness = np.array([config.carriage_drive_k_translation] * 3 + [config.carriage_drive_k_rotation] * 3)
        self._base_drive_stiffness = self.drive_stiffness.copy()
        self.drive_damping = 2.0 * config.carriage_drive_zeta * np.sqrt(self.mass * self.drive_stiffness)

    def set_kappas(self, kappas: float | np.ndarray) -> None:
        """Set six independent stiffness multipliers.

        A scalar is broadcast to all channels for compatibility with the
        original shared-kappa benchmark.  A six-vector is interpreted as
        ``[x, y, z, roll, pitch, yaw]`` and is the preferred interface for
        parameter tuning.
        """

        values = np.asarray(kappas, dtype=float)
        if values.ndim == 0:
            values = np.full(6, float(values))
        if values.shape != (6,) or not np.all(np.isfinite(values)) or np.any(values <= 0.0):
            raise ValueError("kappa must be a positive scalar or a finite six-vector")
        self.kappa_vector = values.copy()
        self.kappa = float(np.mean(values))
        base_stiffness = np.array(
            [self.config.k_translation_base] * 3 + [self.config.k_rotation_base] * 3
        )
        self.stiffness = self.kappa_vector * base_stiffness
        self.damping = 2.0 * self.config.zeta * np.sqrt(self.mass * self.stiffness)

    def set_kappa(self, kappa: float | np.ndarray) -> None:
        """Backward-compatible alias for :meth:`set_kappas`."""

        self.set_kappas(kappa)

    def set_carriage_drive_scale(self, scale: float) -> None:
        """Scale all six virtual-carriage return channels together."""

        if scale <= 0.0:
            raise ValueError("carriage drive scale must be positive")
        self.drive_stiffness = float(scale) * self._base_drive_stiffness
        self.drive_damping = 2.0 * self.config.carriage_drive_zeta * np.sqrt(self.mass * self.drive_stiffness)

    def wrench(self, ee_position: np.ndarray, ee_rotation: np.ndarray, ee_twist: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
        # MuJoCo's spatial Jacobian and angular velocity are expressed in the
        # world frame.  The orientation error must use the same coordinates;
        # using Log(R_ee^T R_c) here would instead express it in the body frame
        # and mixes frames in the rotational spring/damper channels.
        rotation_error = so3_log(self.rotation @ ee_rotation.T)
        displacement = np.concatenate([self.position - ee_position, rotation_error])
        velocity_error = np.concatenate([self.linear_velocity, self.angular_velocity]) - ee_twist
        return saturated_spring(self.stiffness, self.saturation, displacement) + self.damping * velocity_error, displacement

    def advance(
        self,
        dt: float,
        nominal_position: np.ndarray,
        nominal_rotation: np.ndarray,
        nominal_twist: np.ndarray,
        wrench_on_robot: np.ndarray,
    ) -> None:
        rotation_error = so3_log(nominal_rotation @ self.rotation.T)
        displacement = np.concatenate([nominal_position - self.position, rotation_error])
        velocity_error = nominal_twist - np.concatenate([self.linear_velocity, self.angular_velocity])
        drive = self.drive_stiffness * displacement + self.drive_damping * velocity_error
        acceleration = (drive - wrench_on_robot) / self.mass
        self.linear_velocity += dt * acceleration[:3]
        self.angular_velocity += dt * acceleration[3:]
        self.linear_velocity = np.clip(self.linear_velocity, -self.config.max_carriage_speed, self.config.max_carriage_speed)
        self.angular_velocity = np.clip(self.angular_velocity, -self.config.max_carriage_angular_speed, self.config.max_carriage_angular_speed)
        self.position += dt * self.linear_velocity
        self.rotation = integrate_orientation(self.rotation, self.angular_velocity, dt)


def _torque_actuated_xml(menagerie: Path, contact_time_constant_s: float) -> str:
    """Reuse the official Panda geometry while replacing only arm actuation."""

    panda_path = menagerie / "franka_emika_panda" / "panda.xml"
    text = panda_path.read_text()
    torque_actuators = "\n".join(
        f'<motor name="torque_{index}" joint="joint{index}" ctrllimited="true" ctrlrange="{-limit:g} {limit:g}" forcelimited="true" forcerange="{-limit:g} {limit:g}"/>'
        for index, limit in enumerate(TORQUE_LIMITS, start=1)
    )
    replacement = f"<actuator>\n{torque_actuators}\n</actuator>\n\n  <keyframe>"
    text, count = re.subn(r"<actuator>.*?</actuator>\s*<keyframe>", replacement, text, flags=re.DOTALL)
    if count != 1:
        raise RuntimeError("could not replace the official Panda actuator block")
    # The official home keyframe includes eight position-actuator controls.
    # Arm-only torque actuation has seven controls, so retain the initial qpos
    # but remove the now invalid actuator-control vector.
    text = re.sub(r'(<key\b[^>]*?)\sctrl="[^"]*"', r"\1", text)
    # The benchmark is explicitly end-effector-only.  Give the hand collision
    # geometry a dedicated collision bit, then let the dynamic test sphere
    # interact with that bit only.  This prevents an obstacle passing through
    # shoulder/elbow links from being mistaken for a six-dimensional
    # end-effector-compliance result.
    hand_collision = '<geom name="hand_collision" mesh="hand_c" class="collision" contype="4" conaffinity="4"/>'
    text, hand_count = text.replace('<geom mesh="hand_c" class="collision"/>', hand_collision), text.count('<geom mesh="hand_c" class="collision"/>')
    if hand_count != 1:
        raise RuntimeError("could not isolate the official Panda hand collision geometry")
    # The include needs to live alongside official meshes so retain its relative
    # asset resolution.  Add a mocap obstacle and carriage visual to worldbody.
    injected = f"""
      <camera name="track" pos="1.25 -1.45 1.05" xyaxes="0.78 0.62 0  -0.18 0.23 0.96"/>
      <body name="moving_obstacle" mocap="true" pos="0 0 1">
        <geom name="moving_obstacle_geom" type="sphere" size="0.040" mass="0" contype="4" conaffinity="4"
          rgba="0.85 0.12 0.12 0.92" friction="0.9 0.05 0.02"
          solref="{contact_time_constant_s:.5f} 1" solimp="0.75 0.90 0.006 0.5 2"/>
      </body>
      <body name="virtual_carriage" mocap="true" pos="0 0 1">
        <geom name="virtual_carriage_geom" type="sphere" size="0.028" mass="0" contype="0" conaffinity="0" rgba="0.10 0.85 0.95 0.65"/>
      </body>
    """
    text = text.replace("  </worldbody>", injected + "  </worldbody>", 1)
    text = text.replace('<option integrator="implicitfast"/>', '<option integrator="implicitfast" timestep="0.004" gravity="0 0 -9.81"/>')
    return text


def make_model(
    menagerie: Path,
    contact_time_constant_s: float = DEFAULT_CONTACT_TIME_CONSTANT_S,
) -> tuple[mujoco.MjModel, mujoco.MjData]:
    xml = _torque_actuated_xml(menagerie, contact_time_constant_s)
    panda_dir = menagerie / "franka_emika_panda"
    assets_dir = panda_dir / "assets"
    assets = {
        str(path.relative_to(assets_dir)): path.read_bytes()
        for path in assets_dir.rglob("*")
        if path.is_file()
    }
    model = mujoco.MjModel.from_xml_string(xml, assets=assets)
    model.opt.timestep = CONTROL_DT
    data = mujoco.MjData(model)
    mujoco.mj_resetDataKeyframe(model, data, 0)
    mujoco.mj_forward(model, data)
    return model, data


def body_twist(model: mujoco.MjModel, data: mujoco.MjData, body_id: int) -> np.ndarray:
    jac_position = np.zeros((3, model.nv))
    jac_rotation = np.zeros((3, model.nv))
    mujoco.mj_jacBody(model, data, jac_position, jac_rotation, body_id)
    return np.concatenate([jac_position[:, :ARM_DOF] @ data.qvel[:ARM_DOF], jac_rotation[:, :ARM_DOF] @ data.qvel[:ARM_DOF]])


def body_jacobian(model: mujoco.MjModel, data: mujoco.MjData, body_id: int) -> np.ndarray:
    jac_position = np.zeros((3, model.nv))
    jac_rotation = np.zeros((3, model.nv))
    mujoco.mj_jacBody(model, data, jac_position, jac_rotation, body_id)
    return np.vstack([jac_position[:, :ARM_DOF], jac_rotation[:, :ARM_DOF]])


def contact_diagnostics(model: mujoco.MjModel, data: mujoco.MjData, obstacle_geom_id: int) -> tuple[bool, float, float]:
    touching = False
    force_norm = 0.0
    max_penetration = 0.0
    contact_force = np.zeros(6)
    for index in range(data.ncon):
        contact = data.contact[index]
        if contact.geom1 != obstacle_geom_id and contact.geom2 != obstacle_geom_id:
            continue
        touching = True
        mujoco.mj_contactForce(model, data, index, contact_force)
        force_norm = max(force_norm, float(np.linalg.norm(contact_force[:3])))
        max_penetration = max(max_penetration, max(0.0, -float(contact.dist)))
    return touching, force_norm, max_penetration


def torque_feasible_scale(bias: np.ndarray, wrench_torque: np.ndarray) -> float:
    """Largest nonnegative scalar keeping ``bias + scale*wrench`` feasible.

    This is an analytic per-frame projection of the virtual wrench into the
    available joint-torque box.  Unlike output clipping, it preserves the
    wrench direction as far as possible and makes the motor safety constraint
    part of the controller rather than merely a reported failure.
    """

    scale = 1.0
    for gravity, contribution, limit in zip(bias, wrench_torque, TORQUE_LIMITS, strict=True):
        if contribution > EPS:
            scale = min(scale, max(0.0, (limit - gravity) / contribution))
        elif contribution < -EPS:
            scale = min(scale, max(0.0, (-limit - gravity) / contribution))
    return float(np.clip(scale, 0.0, 1.0))


def rate_limit_torque(previous: np.ndarray, desired: np.ndarray, dt: float, config: VMCConfig) -> np.ndarray:
    limits = np.array([config.max_torque_rate_proximal] * 4 + [config.max_torque_rate_distal] * 3)
    return previous + np.clip(desired - previous, -limits * dt, limits * dt)


def obstacle_position(
    time_s: float,
    crossing_position: np.ndarray,
    crossing_direction: np.ndarray,
) -> np.ndarray:
    """A deterministic lateral crossing through the nominal end-effector path."""

    # A fixed world-space transverse crossing.  The direction is computed once
    # from the nominal end-effector velocity and is perpendicular to its
    # horizontal motion, so the obstacle does not follow the robot's path.
    center = crossing_position + 0.14 * (time_s - OBSTACLE_CROSSING_TIME_S) * crossing_direction
    center[2] += 0.012
    return center


def _safe_scalar(value: np.ndarray | float) -> float:
    return float(np.asarray(value))


def run_episode(
    menagerie: Path,
    kappa: float,
    render_gif: bool,
    output_dir: Path,
    config: VMCConfig | None = None,
    obstacle_enabled: bool = True,
    contact_time_constant_s: float = DEFAULT_CONTACT_TIME_CONSTANT_S,
) -> dict[str, Any]:
    model, data = make_model(menagerie, contact_time_constant_s)
    hand_id = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, "hand")
    obstacle_geom_id = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_GEOM, "moving_obstacle_geom")
    obstacle_mocap_id = model.body_mocapid[mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, "moving_obstacle")]
    carriage_mocap_id = model.body_mocapid[mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, "virtual_carriage")]
    if min(hand_id, obstacle_geom_id, obstacle_mocap_id, carriage_mocap_id) < 0:
        raise RuntimeError("required Panda body/visual IDs were not found")

    ee_position0 = data.xpos[hand_id].copy()
    ee_rotation0 = data.xmat[hand_id].reshape(3, 3).copy()
    nominal = NominalReference(model, data, hand_id)
    crossing_position, _, crossing_linear_velocity, _ = nominal.sample(OBSTACLE_CROSSING_TIME_S)
    horizontal_velocity = crossing_linear_velocity.copy()
    horizontal_velocity[2] = 0.0
    horizontal_norm = float(np.linalg.norm(horizontal_velocity))
    if horizontal_norm < 1e-6:
        crossing_direction = np.array([0.0, 1.0, 0.0])
    else:
        crossing_direction = np.array(
            [-horizontal_velocity[1], horizontal_velocity[0], 0.0]
        ) / horizontal_norm
    controller = SixDVirtualCarriage(config or VMCConfig(), kappa, ee_position0, ee_rotation0)

    renderer: mujoco.Renderer | None = None
    frames: list[np.ndarray] = []
    if render_gif:
        renderer = mujoco.Renderer(model, height=480, width=640)
    render_stride = max(1, round(1.0 / (RENDER_FPS * CONTROL_DT)))

    log: dict[str, list[Any]] = {key: [] for key in (
        "time", "track_position", "track_orientation", "ee_speed", "nominal_speed", "surge", "acceleration", "jerk",
        "torque_command", "torque_applied", "torque_ratio", "contact", "contact_force", "penetration", "carriage_error",
    )}
    previous_twist = np.zeros(6)
    previous_acceleration = np.zeros(6)
    previous_torque = data.qfrc_bias[:ARM_DOF].copy()
    had_contact = False
    steps = int(SIM_TIME_S / CONTROL_DT)

    for step in range(steps):
        time_s = step * CONTROL_DT
        nominal_position, nominal_rotation, nominal_linear, nominal_angular = nominal.sample(time_s)
        nominal_twist = np.concatenate([nominal_linear, nominal_angular])
        data.mocap_pos[obstacle_mocap_id] = (
            obstacle_position(time_s, crossing_position, crossing_direction)
            if obstacle_enabled
            else np.array([2.0, 2.0, 2.0])
        )
        data.mocap_quat[obstacle_mocap_id] = np.array([1.0, 0.0, 0.0, 0.0])
        data.mocap_pos[carriage_mocap_id] = controller.position
        data.mocap_quat[carriage_mocap_id] = np.array([1.0, 0.0, 0.0, 0.0])

        ee_position = data.xpos[hand_id].copy()
        ee_rotation = data.xmat[hand_id].reshape(3, 3).copy()
        ee_twist = body_twist(model, data, hand_id)
        wrench, carriage_error = controller.wrench(ee_position, ee_rotation, ee_twist)
        jacobian = body_jacobian(model, data, hand_id)
        bias_torque = data.qfrc_bias[:ARM_DOF].copy()
        wrench_torque = jacobian.T @ wrench
        raw_torque = bias_torque + wrench_torque
        wrench_scale = torque_feasible_scale(bias_torque, wrench_torque)
        feasible_torque = bias_torque + wrench_scale * wrench_torque
        applied_torque = np.clip(
            rate_limit_torque(previous_torque, feasible_torque, CONTROL_DT, controller.config),
            -TORQUE_LIMITS,
            TORQUE_LIMITS,
        )
        data.ctrl[:ARM_DOF] = applied_torque
        controller.advance(CONTROL_DT, nominal_position, nominal_rotation, nominal_twist, wrench)
        mujoco.mj_step(model, data)

        contact, contact_force, penetration = contact_diagnostics(model, data, obstacle_geom_id)
        had_contact = had_contact or contact
        acceleration = (ee_twist - previous_twist) / CONTROL_DT
        jerk = (acceleration - previous_acceleration) / CONTROL_DT
        direction = nominal_linear / (np.linalg.norm(nominal_linear) + EPS)
        surge = max(0.0, float(np.dot(ee_twist[:3], direction) - np.linalg.norm(nominal_linear)))
        tracking_rotation = so3_log(nominal_rotation @ ee_rotation.T)

        log["time"].append(time_s)
        log["track_position"].append(float(np.linalg.norm(ee_position - nominal_position)))
        log["track_orientation"].append(float(np.linalg.norm(tracking_rotation)))
        log["ee_speed"].append(float(np.linalg.norm(ee_twist[:3])))
        log["nominal_speed"].append(float(np.linalg.norm(nominal_linear)))
        log["surge"].append(surge)
        log["acceleration"].append(float(np.linalg.norm(acceleration[:3])))
        log["jerk"].append(float(np.linalg.norm(jerk[:3])))
        log["torque_command"].append(raw_torque.tolist())
        log["torque_applied"].append(applied_torque.tolist())
        log["torque_ratio"].append(float(np.max(np.abs(applied_torque) / TORQUE_LIMITS)))
        log.setdefault("wrench_scale", []).append(wrench_scale)
        log["contact"].append(contact)
        log["contact_force"].append(contact_force)
        log["penetration"].append(penetration)
        log["carriage_error"].append(carriage_error.tolist())
        previous_twist = ee_twist
        previous_acceleration = acceleration
        previous_torque = applied_torque

        if renderer is not None and step % render_stride == 0:
            renderer.update_scene(data, camera="track")
            frames.append(renderer.render().copy())

    if renderer is not None:
        renderer.close()
        gif_path = output_dir / f"vmc_kappa_{kappa:.2f}.gif"
        iio.imwrite(gif_path, np.stack(frames), duration=1.0 / RENDER_FPS, loop=0)
    else:
        gif_path = None

    array_log = {name: np.asarray(values) for name, values in log.items()}
    post_mask = array_log["time"] >= INTERVENTION_TIME_S
    torque_command = array_log["torque_command"]
    torque_applied = array_log["torque_applied"]
    contact_mask = array_log["contact"].astype(bool)
    summary: dict[str, Any] = {
        "kappa": kappa,
        "config": asdict(controller.config),
        "model": "official mujoco_menagerie/franka_emika_panda with torque actuators",
        "reference": "deterministic fixed end-effector reaching proxy; replaceable by fixed WBC reference",
        "intervention_time_s": INTERVENTION_TIME_S,
        "contact_time_constant_s": contact_time_constant_s,
        "obstacle_enabled": obstacle_enabled,
        "contact_observed": bool(had_contact),
        "tracking": {
            "post_intervention_position_rmse_m": _safe_scalar(np.sqrt(np.mean(array_log["track_position"][post_mask] ** 2))),
            "post_intervention_position_max_m": _safe_scalar(np.max(array_log["track_position"][post_mask])),
            "post_intervention_orientation_rmse_rad": _safe_scalar(np.sqrt(np.mean(array_log["track_orientation"][post_mask] ** 2))),
            "final_position_error_m": _safe_scalar(array_log["track_position"][-1]),
        },
        "motion": {
            "post_intervention_speed_p50_mps": _safe_scalar(np.quantile(array_log["ee_speed"][post_mask], 0.50)),
            "post_intervention_speed_p95_mps": _safe_scalar(np.quantile(array_log["ee_speed"][post_mask], 0.95)),
            "post_intervention_speed_max_mps": _safe_scalar(np.max(array_log["ee_speed"][post_mask])),
            "forward_surge_max_mps": _safe_scalar(np.max(array_log["surge"][post_mask])),
            "acceleration_peak_mps2": _safe_scalar(np.max(array_log["acceleration"][post_mask])),
            "jerk_peak_mps3": _safe_scalar(np.max(array_log["jerk"][post_mask])),
        },
        "torque": {
            "unconstrained_peak_nm": _safe_scalar(np.max(np.abs(torque_command))),
            "applied_peak_nm": _safe_scalar(np.max(np.abs(torque_applied))),
            "applied_peak_ratio": _safe_scalar(np.max(array_log["torque_ratio"])),
            "hard_limit_fraction": _safe_scalar(np.mean(np.isclose(np.abs(torque_applied), TORQUE_LIMITS[None, :], rtol=0.0, atol=1e-5))),
            "mean_wrench_feasibility_scale": _safe_scalar(np.mean(array_log["wrench_scale"])),
            "minimum_wrench_feasibility_scale": _safe_scalar(np.min(array_log["wrench_scale"])),
        },
        "contact_diagnostics": {
            "duration_s": _safe_scalar(np.sum(contact_mask) * CONTROL_DT),
            "peak_force_n": _safe_scalar(np.max(array_log["contact_force"])),
            "impulse_ns": _safe_scalar(np.sum(array_log["contact_force"]) * CONTROL_DT),
            "max_penetration_m": _safe_scalar(np.max(array_log["penetration"])),
        },
        "gif": str(gif_path) if gif_path else None,
    }
    np.savez_compressed(output_dir / f"vmc_kappa_{kappa:.2f}_trace.npz", **array_log)
    (output_dir / f"vmc_kappa_{kappa:.2f}_summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    return summary


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--menagerie", required=True, type=Path, help="Path to mujoco_menagerie checkout")
    parser.add_argument("--output-dir", required=True, type=Path)
    parser.add_argument("--kappas", nargs="+", type=float, default=[0.3, 0.5, 0.75, 1.0, 1.5, 2.0])
    parser.add_argument(
        "--torque-rate-scale",
        type=float,
        default=1.0,
        help="Scale the common proximal/distal torque-rate limits for a paired slew scan.",
    )
    parser.add_argument(
        "--damping-ratio",
        type=float,
        default=VMCConfig().zeta,
        help="Common six-dimensional virtual spring damping ratio for a paired damping scan.",
    )
    parser.add_argument(
        "--carriage-drive-scale",
        type=float,
        default=1.0,
        help="Scale nominal-reference-to-carriage stiffness in all six channels.",
    )
    parser.add_argument(
        "--wrench-saturation-scale",
        type=float,
        default=1.0,
        help="Scale all translational and rotational nonlinear-spring saturation bounds.",
    )
    parser.add_argument(
        "--contact-time-constant",
        type=float,
        default=DEFAULT_CONTACT_TIME_CONSTANT_S,
        help="MuJoCo obstacle-contact solver time constant in seconds; fixture calibration parameter.",
    )
    parser.add_argument(
        "--virtual-mass-scale",
        type=float,
        default=1.0,
        help="Common scale for the virtual carriage translational mass and rotational inertia.",
    )
    parser.add_argument(
        "--carriage-speed-scale",
        type=float,
        default=1.0,
        help="Common scale for virtual carriage linear and angular speed limits.",
    )
    parser.add_argument(
        "--carriage-drive-damping-ratio",
        type=float,
        default=VMCConfig().carriage_drive_zeta,
        help="Damping ratio of the fixed-reference-to-virtual-carriage dynamics.",
    )
    parser.add_argument(
        "--disable-obstacle",
        action="store_true",
        help="Run the paired no-contact nominal tracking calibration.",
    )
    parser.add_argument("--render-gif", action="store_true", help="Render one GIF for every evaluated kappa")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    if not (args.menagerie / "franka_emika_panda" / "panda.xml").is_file():
        raise FileNotFoundError("--menagerie must contain franka_emika_panda/panda.xml")
    if min(
        args.torque_rate_scale,
        args.damping_ratio,
        args.carriage_drive_scale,
        args.wrench_saturation_scale,
        args.contact_time_constant,
        args.virtual_mass_scale,
        args.carriage_speed_scale,
        args.carriage_drive_damping_ratio,
    ) <= 0.0:
        raise ValueError("all positive controller scales must be greater than zero")
    args.output_dir.mkdir(parents=True, exist_ok=True)
    config = replace(
        VMCConfig(),
        max_torque_rate_proximal=VMCConfig().max_torque_rate_proximal * args.torque_rate_scale,
        max_torque_rate_distal=VMCConfig().max_torque_rate_distal * args.torque_rate_scale,
        zeta=args.damping_ratio,
        carriage_drive_k_translation=(
            VMCConfig().carriage_drive_k_translation * args.carriage_drive_scale
        ),
        carriage_drive_k_rotation=(
            VMCConfig().carriage_drive_k_rotation * args.carriage_drive_scale
        ),
        max_force=VMCConfig().max_force * args.wrench_saturation_scale,
        max_moment=VMCConfig().max_moment * args.wrench_saturation_scale,
        virtual_mass=VMCConfig().virtual_mass * args.virtual_mass_scale,
        virtual_inertia=VMCConfig().virtual_inertia * args.virtual_mass_scale,
        max_carriage_speed=VMCConfig().max_carriage_speed * args.carriage_speed_scale,
        max_carriage_angular_speed=(
            VMCConfig().max_carriage_angular_speed * args.carriage_speed_scale
        ),
        carriage_drive_zeta=args.carriage_drive_damping_ratio,
    )
    summaries = [
        run_episode(
            args.menagerie,
            kappa,
            args.render_gif,
            args.output_dir,
            config,
            obstacle_enabled=not args.disable_obstacle,
            contact_time_constant_s=args.contact_time_constant,
        )
        for kappa in args.kappas
    ]
    matrix = {
        "protocol": {
            "control_dt_s": CONTROL_DT,
            "simulation_time_s": SIM_TIME_S,
            "torque_rate_scale": args.torque_rate_scale,
            "damping_ratio": args.damping_ratio,
            "carriage_drive_scale": args.carriage_drive_scale,
            "wrench_saturation_scale": args.wrench_saturation_scale,
            "obstacle_enabled": not args.disable_obstacle,
            "contact_time_constant_s": args.contact_time_constant,
            "virtual_mass_scale": args.virtual_mass_scale,
            "carriage_speed_scale": args.carriage_speed_scale,
            "carriage_drive_damping_ratio": args.carriage_drive_damping_ratio,
        },
        "runs": summaries,
    }
    (args.output_dir / "evaluation_matrix.json").write_text(json.dumps(matrix, indent=2) + "\n")
    print(json.dumps(matrix, indent=2))


if __name__ == "__main__":
    # EGL is supplied by the server run command; do not override a caller's
    # preferred backend (for example glfw during local debugging).
    os.environ.setdefault("MUJOCO_GL", "egl")
    main()
